#!/usr/bin/env python3
"""Regenerate the interface-name table from the server project's ConstLib.

An interface arrives at an agent as a bare number — `{"id": 300}` — and a number is
not something you can reason about. The cache's own interface names are in
`org.rs09.consts.Components` in ConstLib, the constant table the 2009scape server
already depends on; the client cannot depend on it (separate build, no maven repo for
it), so the table is extracted once and committed as a resource.

Usage:

    python3 -I scripts/gen-interface-names.py \\
        ~/.m2/repository/org/rs09/consts/ConstLib/1.4.26/ConstLib-1.4.26.jar

Needs a JDK's `javap` on PATH (or JAVA_HOME set). Writes
client/src/main/resources/rt4/mcp/interface-names.tsv and prints what changed.
"""

import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile

CLASS = "org/rs09/consts/Components.class"
OUT = pathlib.Path(__file__).resolve().parent.parent / (
    "client/src/main/resources/rt4/mcp/interface-names.tsv"
)
CONSTANT = re.compile(r"int ([A-Za-z0-9_]+) = (-?\d+);")


def javap() -> str:
    """The `javap` to run: JAVA_HOME's if it has one, else whatever is on PATH."""
    home = os.environ.get("JAVA_HOME")
    if home:
        candidate = pathlib.Path(home) / "bin" / "javap"
        if candidate.is_file():
            return str(candidate)
    found = shutil.which("javap")
    if found is None:
        sys.exit("no javap: put a JDK on PATH or set JAVA_HOME")
    return found


def constants(jar: pathlib.Path) -> "list[tuple[int, str]]":
    """Every `(id, name)` in Components, with the id suffix stripped off the name."""
    with tempfile.TemporaryDirectory() as tmp:
        with zipfile.ZipFile(jar) as archive:
            archive.extract(CLASS, tmp)
        dumped = subprocess.run(
            [javap(), "-constants", "-p", str(pathlib.Path(tmp) / CLASS)],
            check=True,
            capture_output=True,
            text=True,
        ).stdout

    rows = []
    for line in dumped.splitlines():
        match = CONSTANT.search(line)
        if match is None:
            continue
        value = int(match.group(2))
        # The constants are named `<CACHE_NAME>_<id>`; the id is already the key.
        name = re.sub("_" + str(value) + "$", "", match.group(1))
        rows.append((value, name))
    return rows


def main(argv: "list[str]") -> int:
    if len(argv) != 2:
        sys.exit(__doc__)
    rows = constants(pathlib.Path(argv[1]).expanduser())
    if not rows:
        sys.exit("no constants found; is that a ConstLib jar?")

    names = {}
    for value, name in rows:
        if value < 0:
            continue
        names.setdefault(value, name)

    before = OUT.read_text() if OUT.exists() else ""
    lines = ["# id\tname -- generated by scripts/gen-interface-names.py, do not edit"]
    lines += ["%d\t%s" % (value, names[value]) for value in sorted(names)]
    after = "\n".join(lines) + "\n"

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(after)
    print("%s: %d interfaces (%s)" % (OUT, len(names), "unchanged" if before == after else "changed"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
